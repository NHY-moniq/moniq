-- =============================================================================
-- personal_events.is_shift 백필
--
-- 플래그를 도입하기 전에 만들어진 개인 근무 일정은 전부 is_shift = false라,
-- 친목 팀의 "겹치는 근무" 폴백(20260829000001)이 아무것도 찾지 못한다.
-- 제목이 실제 근무 유형 이름과 일치하는 일정을 근무로 표시한다.
--
-- 오프는 제외한다 — 이 앱에서 오프는 "근무 행이 없는 날"이라, 폴백에서
-- 빠져야 그리드에 자연스럽게 'O'로 렌더된다.
-- =============================================================================

UPDATE public.personal_events pe
   SET is_shift = true
 WHERE pe.is_shift = false
   AND (
     -- 어느 팀이든 등록된 근무 유형 이름과 같은 제목
     EXISTS (
       SELECT 1 FROM public.shift_types st
        WHERE st.name = pe.title
     )
     -- 앱 기본 근무 유형 이름 (팀에 등록돼 있지 않아도 개인 근무로 쓰인다)
     OR pe.title IN ('데이', '이브닝', '나이트', '교육')
   )
   AND pe.title NOT IN ('오프', '오프(휴무)', 'OFF', 'Off', 'off');
